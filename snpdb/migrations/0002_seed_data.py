def _create_variant_zygosity_count_partitions(apps, _schema_editor):
    """ VariantZygosityCountCollection is a RelatedModelsPartitionModel: each collection's counts live in an
        INHERITS child table, which the historical model can't create on save """
    VariantZygosityCountCollection = apps.get_model("snpdb", "VariantZygosityCountCollection")
    base_table_name = "snpdb_variantzygositycount"
    for pk in VariantZygosityCountCollection.objects.values_list("pk", flat=True):
        table_name = f"{base_table_name}_collection_{pk}"
        # An identity column's default isn't inherited, so point the child's id at the parent's sequence
        run_sql(f"""
            CREATE TABLE "{table_name}" (
                LIKE {base_table_name} INCLUDING INDEXES,
                CHECK (collection_id = {pk})
            ) INHERITS ({base_table_name});
            ALTER TABLE "{table_name}" ALTER COLUMN id SET DEFAULT nextval('{base_table_name}_id_seq');
        """)


