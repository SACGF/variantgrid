class ParseCytobandTest(TestCase):
    def test_parse_cytoband(self):
        for text, expected in [
            ("11p13", CytobandRange("11", "p13", "p13")),
            ("chrXq28", CytobandRange("X", "q28", "q28")),
            ("17P", CytobandRange("17", "p", "p")),
            ("11p15.5 - p15.4", CytobandRange("11", "p15.5", "p15.4")),
            ("11p11.2-11q12", CytobandRange("11", "p11.2", "q12")),
            ("11p13-12q12", None),  # across chromosomes
            ("21", None),
            ("chr1:100-200", None),
        ]:
            with self.subTest(text=text):
                self.assertEqual(parse_cytoband(text), expected)


class CytobandIntervalTest(TestCase):
    """ Against the cytoband files loaded by the migration - coordinates as in the file, start made 1-based """

    def _interval(self, genome_build, text):
        if interval := parse_cytoband(text).get_interval(genome_build):
            return interval.contig.name, interval.start, interval.end
        return None

    def test_get_interval(self):
        grch37 = GenomeBuild.grch37()
        grch38 = GenomeBuild.grch38()
        for genome_build, text, expected in [
            (grch37, "11p13", ("11", 31000001, 36400000)),
            (grch37, "11p15", ("11", 1, 21700000)),  # every p15.x sub-band
            (grch37, "11p1", ("11", 1, 53700000)),  # region - the whole arm, as every p band is p1x
            (grch37, "11p15.5-p15.4", ("11", 1, 10700000)),
            (grch37, "11p12-p13", ("11", 31000001, 43500000)),  # either order
            (grch37, "17p", ("17", 1, 24000000)),
            (grch38, "11p15.5-p15.4", ("11", 1, 11700000)),
            (grch37, "11p99", None),
            (grch37, "11p13-p99", None),
        ]:
            with self.subTest(genome_build=genome_build.name, text=text):
                self.assertEqual(self._interval(genome_build, text), expected)


class CytobandLevelTest(TestCase):
    """ The levels above the file's bands, generated by migration 0012 """

    def test_levels(self):
        contig = GenomeBuild.grch38().chrom_contig_mappings["1"]
        for name, level in [
            ("p", CytobandLevel.ARM),
            ("p3", CytobandLevel.REGION),
            ("p36", CytobandLevel.BAND),
            ("p36.3", CytobandLevel.SUB_BAND),
            ("p36.33", CytobandLevel.SUB_SUB_BAND),
        ]:
            with self.subTest(name=name):
                self.assertEqual(Cytoband.objects.get(contig=contig, name=name).level, level)

    def test_generated_level_spans_its_children(self):
        contig = GenomeBuild.grch38().chrom_contig_mappings["11"]
        p15 = Cytoband.objects.get(contig=contig, name="p15")
        children = Cytoband.objects.filter(contig=contig, name__startswith="p15.")
        self.assertEqual(p15.start, min(c.start for c in children))
        self.assertEqual(p15.end, max(c.end for c in children))


class CytobandAutocompleteTest(TestCase):
    @classmethod
    def setUpTestData(cls):
        cls.user = User.objects.create_user(username="cytoband_autocomplete_user")
        cls.grch38 = GenomeBuild.grch38()

    def _search(self, q) -> list[str]:
        self.client.force_login(self.user)
        response = self.client.get(reverse("cytoband_autocomplete"),
                                   {"q": q, "forward": json.dumps({"genome_build_id": self.grch38.pk})})
        return [r["text"].split(" ")[0] for r in response.json()["results"]]

    def test_chromosome_and_band_prefix(self):
        self.assertEqual(self._search("11p15")[:3], ["11p15", "11p15.5", "11p15.4"])

    def test_parent_before_child_with_the_same_extent(self):
        self.assertEqual(self._search("chr17p")[:2], ["17p", "17p1"])

    def test_band_on_any_chromosome(self):
        results = self._search("p13")
        self.assertIn("1p13", results)
        self.assertIn("2p13", results)

    def test_not_band_shaped(self):
        self.assertEqual(self._search("BRCA1"), [])


class CytobandSearchAndPageTest(TestCase):
    @classmethod
    def setUpTestData(cls):
        cls.user = User.objects.create_user(username="cytoband_search_user")
        cls.grch38 = GenomeBuild.grch38()

    def test_search_finds_the_band(self):
        urls = {r.preview.internal_url for r in search_data(self.user, "chr11p15").results}
        contig_11 = self.grch38.chrom_contig_mappings["11"]
        self.assertIn(Cytoband.objects.get(contig=contig_11, name="p15").get_absolute_url(), urls)

    def test_search_opens_the_preferred_build(self):
        for genome_build in [GenomeBuild.grch37(), self.grch38]:
            UserSettingsOverride.objects.update_or_create(user=self.user,
                                                          defaults={"default_genome_build": genome_build})
            contig_11 = genome_build.chrom_contig_mappings["11"]
            result = search_data(self.user, "11p13").single_preferred_result()
            self.assertEqual(result.preview.internal_url,
                             Cytoband.objects.get(contig=contig_11, name="p13").get_absolute_url())

    def test_search_ignores_ranges(self):
        self.assertEqual(search_data(self.user, "11p13-p12").results, [])

    def test_contig_page_shows_band(self):
        contig_11 = self.grch38.chrom_contig_mappings["11"]
        self.client.force_login(self.user)
        response = self.client.get(Cytoband.objects.get(contig=contig_11, name="p15").get_absolute_url())
        interval = response.context["cytoband_interval"]
        self.assertEqual((interval.start, interval.end), (1, 22000000))
        selected = [str(c) for c in response.context["cytobands"] if getattr(c, "in_selected_band", False)]
        self.assertEqual(selected, ["11p15.5", "11p15.4", "11p15.3", "11p15.2", "11p15.1"])
