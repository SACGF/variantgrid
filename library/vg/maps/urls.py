"""
`vg map urls`: every URL pattern with its view, owning app and the templates the view names.
Needs Django set up (the resolver imports every urls.py and view module); never queries.

Templates are best-effort: `template_name` on a class-based view, otherwise any '*.html' literal in
the view function's source. API rows are DRF views or paths under an /api/ segment; Public rows match
settings.PUBLIC_PATHS and so bypass GlobalLoginRequiredMiddleware.
"""
import inspect
import re

from django.conf import settings
from django.urls import URLPattern, URLResolver, get_resolver

from library.vg.markdown import MapTable
from library.vg.repo import first_party_packages

INTRO = ("Generated by `vg map urls` (do not edit; run `scripts/vg map urls` after changing a urls.py). "
         "One table per app, in URL order. Templates are the '*.html' names the view's source mentions "
         "(approximate). API = DRF view or /api/ path. Public = matches PUBLIC_PATHS, so no login is required.")

_HTML_RE = re.compile(r"""['"]([\w./-]+\.html)['"]""")


def _view_callable(pattern: URLPattern):
    callback = pattern.callback
    view_class = getattr(callback, "view_class", None) or getattr(callback, "cls", None)
    return view_class or callback


def _qualified_name(view) -> str:
    module = getattr(view, "__module__", "") or ""
    name = getattr(view, "__qualname__", None) or getattr(view, "__name__", None) or type(view).__name__
    return f"{module}:{name}"


def _templates(view) -> str:
    names = []
    template_name = getattr(view, "template_name", None)
    if isinstance(template_name, str):
        names.append(template_name)
    try:
        source = inspect.getsource(view)
    except (OSError, TypeError):
        source = ""
    names.extend(_HTML_RE.findall(source))
    return ", ".join(dict.fromkeys(names))


def _is_api(view, path: str) -> bool:
    if "/api/" in f"/{path}" or path.startswith("api/"):
        return True
    for klass in inspect.getmro(view) if inspect.isclass(view) else ():
        if klass.__module__.startswith("rest_framework"):
            return True
    return False


def _public_matcher():
    patterns = [re.compile(p) for p in getattr(settings, "PUBLIC_PATHS", [])]
    return lambda path: any(p.match("/" + path) for p in patterns)


def _walk(resolver, prefix: str = "", namespace: str = ""):
    for entry in resolver.url_patterns:
        pattern_str = prefix + str(entry.pattern)
        if isinstance(entry, URLResolver):
            ns = f"{namespace}{entry.namespace}:" if entry.namespace else namespace
            yield from _walk(entry, pattern_str, ns)
        elif isinstance(entry, URLPattern):
            yield namespace + (entry.name or ""), pattern_str, entry


def generate(app: str | None = None) -> list[MapTable]:
    is_public = _public_matcher()
    by_app: dict[str, list[list[str]]] = {}
    third_party: dict[str, tuple[str, int]] = {}  # package -> (first pattern, count)
    for name, path, pattern in _walk(get_resolver()):
        view = _view_callable(pattern)
        module = getattr(view, "__module__", "") or ""
        owner = module.split(".")[0]
        if owner not in first_party_packages():
            first, count = third_party.get(owner, (path, 0))
            third_party[owner] = (first, count + 1)
            continue
        if app and owner != app:
            continue
        flags = []
        if _is_api(view, path):
            flags.append("API")
        if is_public(path):
            flags.append("Public")
        by_app.setdefault(owner, []).append([name, f"`{path}`", f"`{_qualified_name(view)}`",
                                             _templates(view), " ".join(flags)])
    columns = ["Name", "Pattern", "View", "Templates", "Flags"]
    tables = [MapTable(title=owner, columns=columns, rows=rows) for owner, rows in sorted(by_app.items())]
    if not app:
        rows = [[package, f"`{first}`", str(count)] for package, (first, count) in sorted(third_party.items())]
        tables.append(MapTable(title="Third-party URL patterns", anchor="third-party",
                               columns=["Package", "First pattern", "Patterns"], rows=rows,
                               note="Admin, auth, registration, DRF docs etc. - counted, not listed."))
    return tables
