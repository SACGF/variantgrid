"""
`vg map settings`: every UPPER_CASE setting, the component file that defines its default and the
environment files that override it. Pure AST over variantgrid/settings/ — nothing is imported, so
secrets are never evaluated.

An override is any module-level assignment to the name, including augmented and subscript
assignments like `SLACK['emoji'] = ...` or `ANNOTATION[BUILD_GRCH38]["enabled"] = True`.
"""
import ast
import re

from library.vg.markdown import MapTable
from library.vg.repo import REPO_ROOT

INTRO = ("Generated by `vg map settings` (do not edit; run `scripts/vg map settings` after adding a setting). "
         "Default is the components/ file that first assigns the name; Overridden by lists the env/ files "
         "(and the developer template) that reassign it or mutate it in place. "
         "`vg settings NAME` (phase 0, pending) shows the resolved value on this box.")

SETTINGS_DIR = REPO_ROOT / "variantgrid" / "settings"
_SETTING_NAME_RE = re.compile(r"^[A-Z][A-Z0-9_]*$")


def assigned_names(path) -> list[tuple[str, bool]]:
    """ (name, mutated_in_place) for every module-level assignment in the file """
    try:
        tree = ast.parse(path.read_bytes())
    except (OSError, SyntaxError):
        return []
    names = []
    for node in tree.body:
        targets, mutated = [], False
        if isinstance(node, ast.Assign):
            targets = node.targets
        elif isinstance(node, (ast.AugAssign, ast.AnnAssign)):
            targets = [node.target]
        elif isinstance(node, ast.Expr) and isinstance(node.value, ast.Call):
            # SETTING.update({...}) / SETTING.append(...) style mutation
            func = node.value.func
            if isinstance(func, ast.Attribute) and func.attr in ("update", "append", "extend", "setdefault", "pop"):
                targets, mutated = [func.value], True
        for target in targets:
            target_mutated = mutated
            while isinstance(target, (ast.Subscript, ast.Attribute)):
                target = target.value
                target_mutated = True
            if isinstance(target, ast.Tuple):
                names.extend((e.id, False) for e in target.elts if isinstance(e, ast.Name))
            elif isinstance(target, ast.Name):
                names.append((target.id, target_mutated))
    return [(name, mutated) for name, mutated in names if _SETTING_NAME_RE.match(name)]


def generate(app: str | None = None) -> list[MapTable]:  # pylint: disable=unused-argument
    defaults: dict[str, str] = {}
    for path in sorted((SETTINGS_DIR / "components").glob("*.py")):
        for name, mutated in assigned_names(path):
            if not mutated:
                defaults.setdefault(name, path.name)

    overrides: dict[str, list[str]] = {}
    env_files = [*sorted((SETTINGS_DIR / "env").glob("*.py")), SETTINGS_DIR / "env_developers" / "_settings_template.py"]
    for path in env_files:
        label = f"{path.parent.name}/{path.name}"
        for name, mutated in assigned_names(path):
            marker = f"{label}~" if mutated else label
            if marker not in overrides.setdefault(name, []):
                overrides[name].append(marker)

    rows = []
    for name in sorted(set(defaults) | set(overrides)):
        rows.append([f"`{name}`", defaults.get(name, "(env only)"), ", ".join(overrides.get(name, []))])
    return [MapTable(title="Settings", columns=["Setting", "Default in", "Overridden by (~ = mutated in place)"], rows=rows)]
