"""
`vg map commands`: every first-party management command grouped by category, with its app, help
line and which apps' models it imports. Needs Django set up (get_commands and importing each command
module); never queries.

Every Command class declares `category = "ops" | "import" | "maintenance" | "one-off" | "dev"`
(claude/plans/agent_system.md §4.6); a command without one (a private-repo command, say) is
categorised from its name prefix and flagged in the map. One-off commands are retired after the
major deploy that no longer needs them.
"""
import ast
from importlib import import_module
from pathlib import Path

from django.core.management import get_commands

from library.vg.markdown import MapTable
from library.vg.repo import first_party_packages

INTRO = ("Generated by `vg map commands` (do not edit; run `scripts/vg map commands` after adding a command). "
         "One table per category, from `Command.category`: **ops** (run on a deployment as part of operating it), "
         "**import** (load reference or user data), **maintenance** (recompute or repair on demand), **one-off** "
         "(a data migration kept until every deployment has run it), **dev** (development and introspection). "
         "A command without a declared category is marked `(guessed)`. Models touched lists the apps whose models "
         "the command module imports.")

CATEGORY_ORDER = ("ops", "import", "maintenance", "one-off", "dev")

_PREFIX_CATEGORIES = (
    (("fix_", "one_off_", "backfill_", "migrate_", "repair_"), "one-off"),
    (("import_", "load_", "download_", "cached_web_resource", "clinvar_", "gnomad_", "vep_"), "import"),
    (("create_fake", "profile_", "benchmark", "test_", "debug_", "vg"), "dev"),
    (("deployment_check", "manual_", "check_", "health", "restart", "celery", "annotation_run"), "ops"),
)


def _guess_category(name: str) -> str:
    for prefixes, category in _PREFIX_CATEGORIES:
        if name.startswith(prefixes) or name in prefixes:
            return category
    return "maintenance"


def _models_touched(module_path: Path) -> str:
    apps_touched = set()
    try:
        tree = ast.parse(module_path.read_bytes())
    except (OSError, SyntaxError):
        return ""
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module:
            parts = node.module.split(".")
            if len(parts) >= 2 and parts[1] == "models" and parts[0] in first_party_packages():
                apps_touched.add(parts[0])
        elif isinstance(node, ast.Import):
            for alias in node.names:
                parts = alias.name.split(".")
                if len(parts) >= 2 and parts[1] == "models" and parts[0] in first_party_packages():
                    apps_touched.add(parts[0])
    return ", ".join(sorted(apps_touched))


def generate(app: str | None = None) -> list[MapTable]:
    by_category: dict[str, list[list[str]]] = {}
    for name, app_name in sorted(get_commands().items()):
        owner = app_name.split(".")[0]
        if owner not in first_party_packages() or (app and owner != app):
            continue
        module_name = f"{app_name}.management.commands.{name}"
        try:
            module = import_module(module_name)
            command_class = getattr(module, "Command", None)
            help_text = (getattr(command_class, "help", "") or module.__doc__ or "").strip().splitlines()
            help_line = help_text[0].strip() if help_text else ""
            category = getattr(command_class, "category", None)
            if command_class is None:
                help_line = help_line or "(helper module, not a command)"
            if not category:
                category = _guess_category(name)
                help_line = f"{help_line} (guessed)".strip()
            path = Path(module.__file__)
        except Exception as e:  # pylint: disable=broad-exception-caught
            help_line, category, path = f"(import failed: {type(e).__name__})", "?", None
        by_category.setdefault(category, []).append([f"`{name}`", owner, help_line,
                                                     _models_touched(path) if path else ""])
    columns = ["Command", "App", "Help", "Models touched"]
    ordered = sorted(by_category, key=lambda c: (CATEGORY_ORDER.index(c) if c in CATEGORY_ORDER else len(CATEGORY_ORDER), c))
    return [MapTable(title=category, columns=columns, rows=by_category[category]) for category in ordered]
