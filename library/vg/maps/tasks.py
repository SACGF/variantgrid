"""
`vg map tasks`: every celery task (decorated function or Task subclass), the queue it routes to and
the modules that enqueue it. Pure AST — no Django, no celery import.

Queue resolution: the decorator's queue= kwarg, else CELERY_TASK_ROUTES in
variantgrid/settings/components/celery_settings.py (parsed, not imported), else the default queue.
"""
import ast
from pathlib import Path

from library.vg.markdown import MapTable
from library.vg.repo import REPO_ROOT, iter_python_files

INTRO = ("Generated by `vg map tasks` (do not edit; run `scripts/vg map tasks` after adding a task). "
         "Queue is the decorator's queue=, else CELERY_TASK_ROUTES, else the default (db_workers). "
         "Enqueued by lists modules calling `.delay/.apply_async/.s/.si/.signature` on the task.")

CELERY_SETTINGS = REPO_ROOT / "variantgrid" / "settings" / "components" / "celery_settings.py"
DEFAULT_QUEUE = "db_workers"
_TASK_DECORATORS = {"task", "shared_task"}
_ENQUEUE_ATTRS = {"delay", "apply_async", "s", "si", "signature", "apply"}


def decorator_name(node) -> str | None:
    func = node.func if isinstance(node, ast.Call) else node
    if isinstance(func, ast.Attribute):
        return func.attr
    if isinstance(func, ast.Name):
        return func.id
    return None


def decorator_queue(node) -> str | None:
    if isinstance(node, ast.Call):
        for keyword in node.keywords:
            if keyword.arg == "queue" and isinstance(keyword.value, ast.Constant):
                return keyword.value.value
    return None


def task_routes() -> dict[str, str]:
    """ task name -> queue, from CELERY_TASK_ROUTES with its {'queue': ...} constants resolved """
    tree = ast.parse(CELERY_SETTINGS.read_bytes())
    constants: dict[str, str] = {}
    routes: dict[str, str] = {}
    for node in tree.body:
        if not isinstance(node, ast.Assign) or len(node.targets) != 1 or not isinstance(node.targets[0], ast.Name):
            continue
        name, value = node.targets[0].id, node.value
        if isinstance(value, ast.Dict):
            keys = [k.value for k in value.keys if isinstance(k, ast.Constant)]
            if "queue" in keys:
                constants[name] = value.values[keys.index("queue")].value
            elif name == "CELERY_TASK_ROUTES":
                for key, val in zip(value.keys, value.values):
                    if isinstance(key, ast.Constant) and isinstance(val, ast.Name):
                        routes[key.value] = constants.get(val.id, val.id)
    return routes


def _is_task_class(node: ast.ClassDef) -> bool:
    return any(decorator_name(base) == "Task" for base in node.bases)


def enqueue_targets(tree) -> set[str]:
    """ Names X such that X.delay(...) / X().apply_async(...) etc. appears in the module """
    names = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Attribute) and node.attr in _ENQUEUE_ATTRS:
            value = node.value
            if isinstance(value, ast.Call):
                value = value.func
            if isinstance(value, ast.Name):
                names.add(value.id)
            elif isinstance(value, ast.Attribute):
                names.add(value.attr)
    return names


def generate(app: str | None = None) -> list[MapTable]:
    routes = task_routes()
    tasks: list[tuple[str, str, str, str]] = []   # app, module, name, queue
    enqueuers: dict[str, set[str]] = {}            # task short name -> modules calling it
    parsed: dict[str, ast.Module] = {}

    for module, path in iter_python_files():
        if not module:
            continue
        try:
            tree = ast.parse(Path(path).read_bytes())
        except (OSError, SyntaxError):
            continue
        parsed[module] = tree
        for node in tree.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                task_decorators = [d for d in node.decorator_list if decorator_name(d) in _TASK_DECORATORS]
                if not task_decorators:
                    continue
                queue = decorator_queue(task_decorators[0]) or routes.get(f"{module}.{node.name}", DEFAULT_QUEUE)
                tasks.append((module.split(".")[0], module, node.name, queue))
            elif isinstance(node, ast.ClassDef) and _is_task_class(node):
                queue = routes.get(f"{module}.{node.name}", DEFAULT_QUEUE)
                tasks.append((module.split(".")[0], module, node.name, queue))

    task_names = {name for _, _, name, _ in tasks}
    for module, tree in parsed.items():
        for name in enqueue_targets(tree) & task_names:
            enqueuers.setdefault(name, set()).add(module)

    by_app: dict[str, list[list[str]]] = {}
    for owner, module, name, queue in sorted(tasks):
        if app and owner != app:
            continue
        callers = sorted(m for m in enqueuers.get(name, ()) if m != module)
        by_app.setdefault(owner, []).append([f"`{module}:{name}`", queue, ", ".join(callers)])
    columns = ["Task", "Queue", "Enqueued by"]
    return [MapTable(title=owner, columns=columns, rows=rows) for owner, rows in sorted(by_app.items())]
