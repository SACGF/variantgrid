"""
`vg map signals`: every first-party Signal() with its documented args, plus every receiver of any
signal (first-party or Django's post_save etc.) with the sender it filters on. Pure AST — no Django.

Receivers are found from `@receiver(signal, sender=X)` decorators and `signal.connect(func)` calls.
"""
import ast
from pathlib import Path

from library.vg.markdown import MapTable
from library.vg.repo import iter_python_files

INTRO = ("Generated by `vg map signals` (do not edit; run `scripts/vg map signals` after adding a signal or "
         "receiver). Args are the trailing comment on the Signal() line. Receivers come from @receiver and "
         ".connect(); the sender is the sender= argument when given.")


def _dotted(node) -> str | None:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        base = _dotted(node.value)
        return f"{base}.{node.attr}" if base else node.attr
    if isinstance(node, ast.Call):
        return _dotted(node.func)
    return None


def _last(name: str | None) -> str:
    return (name or "?").split(".")[-1]


def is_signal_call(node) -> bool:
    return isinstance(node, ast.Call) and _last(_dotted(node.func)) == "Signal"


def _trailing_comment(source_lines: list[str], lineno: int) -> str:
    line = source_lines[lineno - 1]
    _, hash_sign, comment = line.partition("#")
    return comment.strip() if hash_sign else ""


def receiver_signal_names(node) -> list[str]:
    """ Signals named in a @receiver(...) decorator: the first positional (a name or a list) or signal= """
    candidates = []
    if node.args:
        candidates.append(node.args[0])
    for keyword in node.keywords:
        if keyword.arg == "signal":
            candidates.append(keyword.value)
    names = []
    for candidate in candidates:
        elements = candidate.elts if isinstance(candidate, (ast.List, ast.Tuple)) else [candidate]
        names.extend(_last(_dotted(e)) for e in elements)
    return names


def receiver_sender(node) -> str:
    for keyword in node.keywords:
        if keyword.arg == "sender":
            return _dotted(keyword.value) or "?"
    return ""


def generate(app: str | None = None) -> list[MapTable]:
    definitions: list[list[str]] = []
    receivers: dict[str, list[tuple[str, str]]] = {}  # signal short name -> [(receiver module:function, sender)]

    for module, path in iter_python_files():
        if not module:
            continue
        try:
            source = Path(path).read_text(encoding="utf-8")
            tree = ast.parse(source)
        except (OSError, SyntaxError, UnicodeDecodeError):
            continue
        source_lines = source.splitlines()

        for node in tree.body:
            targets = []
            if isinstance(node, ast.Assign) and is_signal_call(node.value):
                targets = [t.id for t in node.targets if isinstance(t, ast.Name)]
            elif isinstance(node, ast.AnnAssign) and is_signal_call(node.value) and isinstance(node.target, ast.Name):
                targets = [node.target.id]
            for target in targets:
                definitions.append([f"`{module}:{target}`", _trailing_comment(source_lines, node.lineno)])

        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                for decorator in node.decorator_list:
                    if isinstance(decorator, ast.Call) and _last(_dotted(decorator.func)) == "receiver":
                        for signal_name in receiver_signal_names(decorator):
                            receivers.setdefault(signal_name, []).append((f"{module}:{node.name}", receiver_sender(decorator)))
            elif isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr == "connect":
                signal_name = _last(_dotted(node.func.value))
                if node.args and (func_name := _dotted(node.args[0])):
                    receivers.setdefault(signal_name, []).append((f"{module}:{func_name}", receiver_sender(node)))

    defined_names = {row[0].split(":")[-1].rstrip("`") for row in definitions}
    definition_rows = []
    for definition_cell, args in sorted(definitions):
        short = definition_cell.split(":")[-1].rstrip("`")
        owner = definition_cell.strip("`").split(".")[0]
        if app and owner != app:
            continue
        receiver_list = sorted(receivers.get(short, []))
        receiver_cells = [f"`{r}`" + (f" (sender={s})" if s else "") for r, s in receiver_list]
        definition_rows.append([definition_cell, args, ", ".join(receiver_cells) or "(none)"])

    framework_rows = []
    for signal_name, receiver_list in sorted(receivers.items()):
        if signal_name in defined_names:
            continue
        for receiver_name, sender in sorted(receiver_list):
            owner = receiver_name.split(".")[0]
            if app and owner != app:
                continue
            framework_rows.append([signal_name, sender, f"`{receiver_name}`"])

    return [
        MapTable(title="First-party signals", anchor="first-party",
                 columns=["Signal", "Args", "Receivers"], rows=definition_rows),
        MapTable(title="Framework and third-party signal receivers", anchor="framework",
                 columns=["Signal", "Sender", "Receiver"], rows=framework_rows,
                 note="Receivers of Django / third-party signals (post_save, pre_delete, m2m_changed, user_logged_in…)."),
    ]
