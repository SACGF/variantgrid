"""
`vg map models`: per app, every concrete model with the mixins it inherits, its outgoing relations,
its non-default managers and (with --counts) an estimated row count from pg_class on this database.
Needs Django set up; never queries without --counts.
"""
from django.apps import apps
from django.db import connection
from django.db.models import Manager

from library.vg.markdown import MapTable
from library.vg.repo import first_party_packages

INTRO = ("Generated by `vg map models` (do not edit; run `scripts/vg map models` after changing a model). "
         "One table per app. Bases lists the mixins and abstract parents a model inherits; "
         "Relations are forward FK / OneToOne / M2M targets; Managers are non-default manager classes.")

_BORING_BASES = {"Model", "object", "Generic"}


def _bases(model) -> str:
    names = []
    for klass in model.__mro__[1:]:
        if klass.__name__ in _BORING_BASES or klass.__module__.startswith(("django.", "builtins")):
            continue
        if klass.__module__.split(".")[0] not in first_party_packages() and not klass.__name__.endswith("Mixin"):
            continue
        names.append(klass.__name__)
    return ", ".join(dict.fromkeys(names))


def _relations(model) -> str:
    targets = []
    for f in model._meta.get_fields(include_hidden=False):
        if f.is_relation and f.concrete and f.related_model is not None:
            suffix = "[]" if f.many_to_many else ""
            targets.append(f"{f.name}→{f.related_model._meta.label}{suffix}")
    return ", ".join(targets)


def _managers(model) -> str:
    names = []
    for manager in model._meta.managers:
        klass = type(manager)
        if klass is Manager or klass.__name__ in ("Manager", "ManagerFromQuerySet"):
            continue
        names.append(f"{manager.name}: {klass.__name__}")
    return ", ".join(dict.fromkeys(names))


def _row_estimates() -> dict[str, int]:
    with connection.cursor() as cursor:
        cursor.execute("SELECT relname, reltuples::bigint FROM pg_class WHERE relkind IN ('r', 'p')")
        return dict(cursor.fetchall())


def generate(counts: bool = False, app: str | None = None) -> list[MapTable]:
    estimates = _row_estimates() if counts else {}
    columns = ["Model", "Bases", "Relations", "Managers"] + (["~Rows"] if counts else [])
    tables = []
    for app_config in sorted(apps.get_app_configs(), key=lambda a: a.label):
        if app_config.name.split(".")[0] not in first_party_packages():
            continue
        if app and app_config.label != app:
            continue
        rows = []
        for model in sorted(app_config.get_models(), key=lambda m: m.__name__):
            row = [f"`{model.__module__}:{model.__name__}`", _bases(model), _relations(model), _managers(model)]
            if counts:
                row.append(f"{estimates.get(model._meta.db_table, 0):,}")
            rows.append(row)
        tables.append(MapTable(title=app_config.label, columns=columns, rows=rows))
    return tables
